"""Fig. 3 -- aggregate the attribute-classifier outputs into the plotted values.

``data/traversals/classifier_outputs/{generator}_{positive,negative}.csv.gz``
hold, for every traversed image, the probabilities of the 47 facial attributes
predicted by ``traversals/attribute_classifier/predict_attributes.py``
(ResNet-18 trained with the code of Lingenfelter & Hand [31]). The traversal strength is encoded
in the file name (``..._<strength>.png``). This script averages them per
strength and writes ``data/traversals/attribute_probabilities.json``, which
``plot_fig3.py`` draws.

    python traversals/fig3_aggregate.py --check    # compare with the shipped json
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "data" / "traversals" / "classifier_outputs"
OUT = REPO / "data" / "traversals" / "attribute_probabilities.json"
ATTRS = {  # name in the figure -> column (Female = 1 - Male)
    "Female": "Male", "Young": "Young", "White": "White", "Blond Hair": "Blond_Hair",
    "Fully Visible Forehead": "Fully_Visible_Forehead", "Wearing Hat": "Wearing_Hat",
}


def aggregate(csv_path: Path) -> dict:
    df = pd.read_csv(csv_path)
    df["strength"] = df["Filename"].str.extract(r"_(-?\d+\.\d+|\d+)\.png$")[0].astype(float)
    g = df.groupby("strength").mean(numeric_only=True)
    values = {}
    for name, col in ATTRS.items():
        v = g[col].to_numpy()
        values[name] = [round(float(x), 6) for x in (1 - v if name == "Female" else v)]
    return {"strength": [float(s) for s in g.index], "values": values}


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="only compare with the shipped json")
    args = p.parse_args()
    res = {"_comment": "Mean predicted attribute probability per traversal strength (group A direction); "
                       "generated by traversals/fig3_aggregate.py from data/traversals/classifier_outputs."}
    for gen in ("arc2face", "infiniteyou"):
        res[gen] = {s: aggregate(SRC / f"{gen}_{s}.csv.gz") for s in ("positive", "negative")}
    if args.check:
        ref = json.loads(OUT.read_text())
        worst = 0.0
        for gen in ("arc2face", "infiniteyou"):
            for s in ("positive", "negative"):
                for name in ATTRS:
                    a, b = np.array(res[gen][s]["values"][name]), np.array(ref[gen][s]["values"][name])
                    worst = max(worst, float(np.abs(a - b).max()))
        print(f"max abs difference with {OUT.name}: {worst:.2e}")
        return
    OUT.write_text(json.dumps(res, indent=1))
    print(f"Saved {OUT}")


if __name__ == "__main__":
    main()
